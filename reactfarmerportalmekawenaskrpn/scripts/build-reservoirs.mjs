// Builds src/reservoirs.js (the tanks farmers choose from when registering)
// from ../reservoirs_data.json at the repo root. Keeps the fixed details only, not the daily readings.
// Run: npm run reservoirs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const data = JSON.parse(readFileSync(here('../../reservoirs_data.json'), 'utf8'));

const title = (s) => s.toLowerCase().replace(/\b\w/g, (c) => c.toUpperCase());
const district = (s) => title(s.replace('ANURADAPURA', 'ANURADHAPURA'));
const DISPLAY = { 'Senanayaka Sam': 'Senanayaka Sam (Senanayake Samudraya)' };
// Other spellings farmers may search for: the Mahaweli Authority names (mahawelitanks table).
// PSS (Parakrama Samudraya) and Tissawewa are left out on purpose.
const AKA = {
  'Handapanagala': 'Hadapanagala',
  'Nuwara Wewa': 'Nuwarawewa',
  'Thuruwila tank': 'Thuruvila',
  'Basavakkulama (Abaya wewa)': 'Basawakkulama',
  'Rajangana': 'Rajanganaya',
  'Vendrasan': 'Vendrason',
  'Alikota ara': 'Alikotaara',
};
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const rows = data.map((r) => `  { id: ${q(slug(r.name))}, name: ${q(DISPLAY[r.name] || r.name)}, district: ${q(district(r.district))}, `
  + `division: ${q(r.division)}, type: ${q(r.type)}, lat: ${r.latitude}, lon: ${r.longitude}${AKA[r.name] ? `, aka: ${q(AKA[r.name])}` : ''} },`);

writeFileSync(here('../src/reservoirs.js'), `// Irrigation tanks and reservoirs farmers can choose when registering.
// Generated by scripts/build-reservoirs.mjs from reservoirs_data.json. Do not edit by hand: run \`npm run reservoirs\`.
export const RESERVOIRS = [
${rows.join('\n')}
];
`);
console.log(`Wrote ${rows.length} tanks to src/reservoirs.js`);
